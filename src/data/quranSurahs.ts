/**
 * Format helper for EveryAyah filenames:
 * Surah: 3 digits (e.g. 001)
 * Ayah: 3 digits (e.g. 007)
 */
export function getEveryAyahAudioUrl(reciterFolder: string, surahNumber: number, ayahNumber: number): string {
  const sStr = String(surahNumber).padStart(3, '0');
  const aStr = String(ayahNumber).padStart(3, '0');
  return `https://everyayah.com/data/${reciterFolder}/${sStr}${aStr}.mp3`;
}

/**
 * Format helper for full surah audio URLs:
 */
export function getFullSurahAudioUrl(serverBaseUrl: string, surahNumber: number): string {
  const sStr = String(surahNumber).padStart(3, '0');
  return `${serverBaseUrl}${sStr}.mp3`;
}
