/**
 * Universal translation resolver supporting snake_case, camelCase and multi-tier fallbacks.
 */
export function getTranslation(lang: SupportedLanguage, key: string, fallback?: string): string {
  if (!key) return fallback || '';
  const langDict = TRANSLATIONS[lang] || TRANSLATIONS.ar;
  if (langDict && langDict[key]) return langDict[key];

  // Try snake_case if key is camelCase (e.g. navQuran -> nav_quran)
  const snake = key.replace(/[A-Z]/g, (l) => `_${l.toLowerCase()}`);
  if (langDict && langDict[snake]) return langDict[snake];

  // Try camelCase if key is snake_case (e.g. nav_quran -> navQuran)
  const camel = key.replace(/_([a-z])/g, (_, l) => l.toUpperCase());
  if (langDict && langDict[camel]) return langDict[camel];

  // If in English and not found, check en explicitly
  if (lang === 'en' && TRANSLATIONS.en) {
    if (TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];
    if (TRANSLATIONS.en[snake]) return TRANSLATIONS.en[snake];
    if (TRANSLATIONS.en[camel]) return TRANSLATIONS.en[camel];
  }

  // Fallback to English dictionary if non-Arabic and not found in target
  if (lang !== 'ar' && lang !== 'en' && TRANSLATIONS.en) {
    if (TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];
    if (TRANSLATIONS.en[snake]) return TRANSLATIONS.en[snake];
    if (TRANSLATIONS.en[camel]) return TRANSLATIONS.en[camel];
  }

  // Fallback to Arabic dictionary
  if (TRANSLATIONS.ar) {
    if (TRANSLATIONS.ar[key]) return TRANSLATIONS.ar[key];
    if (TRANSLATIONS.ar[snake]) return TRANSLATIONS.ar[snake];
    if (TRANSLATIONS.ar[camel]) return TRANSLATIONS.ar[camel];
  }

  return fallback !== undefined ? fallback : key;
}

